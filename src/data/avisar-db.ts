export type Risk = "CRÍTICO" | "ALTO" | "MEDIO"
export type RepairStatus = "Pendiente de revisión" | "Reparación programada" | "Reparación realizada"
export type Channel = "WhatsApp" | "E-mail"

/* ---------- Tablas ---------- */

export interface DbUser {
  id: string
  name: string
  fullName: string
  email: string
  password: string // solo demo: en producción nunca se guarda en texto plano
  phone: string
  province: string
  scenario: string
  createdAt: string
  consent: { accepted: boolean; acceptedAt: string; text: string }
}

export interface DbVehicle {
  id: string
  plate: string
  plateNormalized: string
  vin: string
  brand: string
  model: string
  version: string
  year: string
  /** Provincia del registro seccional (DNRPA). Solo en los vehículos tomados del parque real. */
  province?: string
}

/** Relación patente / VIN → id del dueño (cuenta de AvisAR). */
export interface DbOwnership {
  id: string
  vehicleId: string
  ownerId: string
  plate: string
  vin: string
  role: "titular" | "usuario habitual"
  since: string
  until: string | null
  source: string
  verified: boolean
}

/** Campaña con alcance por marca, modelo y rango de años. Compatible con el tipo Recall de App.tsx. */
export interface DbCampaign {
  id: string
  campaign: string
  brand: string
  model: string
  yearFrom: number
  yearTo: number
  title: string
  component: string
  risk: Risk
  description: string
  danger: string
  action: string
  date: string
  publishedAt: string
  contact: string
}

export interface DbRepairStatus {
  vehicleId: string
  campaignId: string
  ownerId: string
  status: RepairStatus
  updatedAt: string
}

export interface DbAlert {
  id: string
  ownerId: string
  vehicleId: string
  vehicle: string
  plate: string
  channel: Channel
  destination: string
  active: boolean
}

export interface DbQuery {
  ownerId: string
  vehicleId: string
  consultedAt: string
}

